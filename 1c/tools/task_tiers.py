def tier_of(num, title):
    """Возвращает уровень задания: 'ядро' | 'расширение' | 'резерв'."""
    if num in EXCEPTIONS:
        return EXCEPTIONS[num]
    low = title.strip().lower()
    for pat in RESERVE:
        if re.search(pat, low):
            return "резерв"
    for pat in EXPANSION:
        if re.search(pat, low):
            return "расширение"
    return "ядро"


