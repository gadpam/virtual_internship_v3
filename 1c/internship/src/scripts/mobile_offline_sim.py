#!/usr/bin/env python3
"""Эмуляция офлайн-сценария task_41 (мобильная инвентаризация).

Обоснование выбора прототипа: мобильной платформы в стенде нет, поэтому
прототипируется самая рискованная часть — офлайн-очередь и синхронизация,
а не экраны. Устройство: локальный снимок (товар, остаток по учёту),
кладовщик вводит факт; правки копятся очередью; при связи очередь уходит
на сервер, конфликты разрешаются правилами из документации task_41.

Запуск: src/scripts/.venv/bin/python src/scripts/mobile_offline_sim.py
"""

from __future__ import annotations


def estimate_mb(rows: int, bytes_per_row: int) -> float:
    return rows * bytes_per_row / 1_000_000


def main() -> None:
    # Оценка объёма на устройстве при 100 000 позиций
    nomenclature = estimate_mb(100_000, 220)   # наименование+артикул+штрихкод+единица
    barcodes = estimate_mb(130_000, 60)        # у товара бывает >1 штрихкода
    balances = estimate_mb(40_000, 48)         # активные пары склад×товар, не все 100k×5
    print(f"номенклатура 100k: {nomenclature:.1f} МБ; штрихкоды: {barcodes:.1f} МБ; "
          f"остатки активных пар: {balances:.1f} МБ")
    total = nomenclature + barcodes + balances
    print(f"итого снимок на устройство: ~{total:.0f} МБ (без картинок товаров)")

    # Офлайн-очередь: (товар, факт, версия снимка устройства)
    server = {"SKU-1": {"учёт": 10, "версия": 3}}
    device_queue = [
        {"sku": "SKU-1", "факт": 9, "версия_снимка": 3},   # конфликта нет
        {"sku": "SKU-2", "факт": 5, "версия_снимка": 1},
    ]
    # Пока устройство было офлайн, сервер принял поступление по SKU-1 (+2)
    server["SKU-1"] = {"учёт": 12, "версия": 4}

    for op in device_queue:
        current = server.get(op["sku"])
        if current is None:
            print(f"{op['sku']}: новый для сервера — принять, товар завести задачей сверки")
        elif op["версия_снимка"] < current["версия"]:
            print(f"{op['sku']}: КОНФЛИКТ — снимок v{op['версия_снимка']} старше сервера "
                  f"v{current['версия']} (учёт {current['учёт']}, факт устройства {op['факт']}): "
                  f"сервер не перезаписываем, расхождение уходит в акт инвентаризации")
        else:
            print(f"{op['sku']}: принято, расхождение {op['факт'] - current['учёт']} в акт")


if __name__ == "__main__":
    main()
