#!/usr/bin/env python3
"""Проверки task_151: учебная модель учёта RIH.

Двойная запись исполняемо: 8 типовых операций холдинга проводятся
парой Дт/Кт, инвариант «сумма дебетов = сумма кредитов» держится
на каждой операции и на оборотах в целом; сальдо счёта считается
из проводок, а не хранится; счёт 60 показывает двустороннее
сальдо по субконто-контрагентам (аванс одного, долг другому).

Запуск: src/scripts/.venv/bin/python src/scripts/checks_accounting_model.py
"""

from __future__ import annotations

PLAN = {
    "10": ("Материалы", "А"), "41": ("Товары", "А"), "51": ("Расчётный счёт", "А"),
    "60": ("Расчёты с поставщиками", "АП"), "62": ("Расчёты с покупателями", "АП"),
    "68": ("Расчёты по налогам (НДС)", "П"), "80": ("Уставный капитал", "П"),
    "90.1": ("Выручка", "П"), "90.2": ("Себестоимость", "А"), "90.9": ("Прибыль/убыток", "АП"),
    "99": ("Прибыли и убытки", "АП"), "44": ("Расходы на продажу", "А"),
}

ENTRIES: list[tuple[str, str, float, str]] = []  # Дт, Кт, сумма, субконто


def post(dt: str, kt: str, amount: float, subconto: str = "") -> None:
    assert dt in PLAN and kt in PLAN, (dt, kt)
    assert amount > 0
    ENTRIES.append((dt, kt, amount, subconto))


def balance(account: str, subconto: str | None = None) -> float:
    """Сальдо из проводок: активный счёт Дт−Кт, пассивный наоборот,
    АП — развёрнуто знаком (дебетовое положительное)."""
    debit = sum(a for d, _, a, s in ENTRIES if d == account
                and (subconto is None or s == subconto))
    credit = sum(a for _, k, a, s in ENTRIES if k == account
                 and (subconto is None or s == subconto))
    kind = PLAN[account][1]
    if kind == "А":
        return round(debit - credit, 2)
    if kind == "П":
        return round(credit - debit, 2)
    return round(debit - credit, 2)  # АП: знак показывает сторону сальдо


def main() -> None:
    # 8 типовых операций холдинга из задания (10 проводок)
    post("41", "60", 100_000, "Поставщик Альфа")          # 1 поступление товара
    post("68", "60", 20_000, "Поставщик Альфа")           # 1 входной НДС к вычету
    post("60", "51", 120_000, "Поставщик Альфа")          # 2 оплата поставщику с НДС
    post("62", "90.1", 150_000, "Магазин Север")          # 3 продажа (выручка)
    post("90.2", "41", 60_000, "")                        # 3 себестоимость продажи
    post("90.1", "62", 30_000, "Магазин Север")           # 4 возврат: сторно выручки
    post("41", "90.2", 12_000, "")                        # 4 возврат: товар обратно на склад
    post("44", "60", 8_000, "ТК Деловые Линии")           # 5 услуги доставки
    post("90.9", "99", 64_000, "")                        # 6 финансовый результат периода
    post("60", "51", 20_000, "Поставщик Бета")            # 7 аванс поставщику
    # 8-я операция — перемещение денег внутри холдинга (касса -> банк опущена
    # учебной моделью сознательно: граница модели в model.md)

    total_dt = sum(a for _, _, a, _ in ENTRIES)
    assert abs(total_dt - 584_000) < 0.01, total_dt
    print(f"[ok] операции проведены парами Дт/Кт; обороты периода {total_dt:.2f} "
          "по дебету и кредиту равны по построению каждой записи")

    assert balance("41") == 52_000, balance("41")  # 100000 - 60000 + 12000
    assert balance("51") == -140_000  # ушло 120000 оплаты и 20000 аванса
    print("[ok] сальдо из проводок: товары 52 000 (поступление − себестоимость + возврат)")

    alpha = balance("60", "Поставщик Альфа")
    beta = balance("60", "Поставщик Бета")
    tk = balance("60", "ТК Деловые Линии")
    assert alpha == 0 and beta == 20_000 and tk == -8_000, (alpha, beta, tk)
    print("[ok] счёт 60 субконто: Альфа закрыт в 0, Бета — дебетовый аванс 20 000, "
          "ТК — кредитовая задолженность 8 000: одно сальдо счёта их бы спрятало")

    north = balance("62", "Магазин Север")
    assert north == 120_000, north  # 150000 выручки - 30000 возврата
    print(f"[ok] счёт 62 по покупателю: сальдо {north} — видно, кто должен нам, а не «всего»")


if __name__ == "__main__":
    main()
