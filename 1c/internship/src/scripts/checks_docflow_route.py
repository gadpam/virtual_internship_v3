#!/usr/bin/env python3
"""Проверки task_163: маршрут договора как state machine (модель ДО).

Этапы последовательны, роли вместо фамилий, одно ветвление по
лимиту суммы, возвраты на доработку к инициатору, сроки этапов
с эскалацией. Проектирование — от конечного состояния «подписан
обеими сторонами» назад.

Запуск: src/scripts/.venv/bin/python src/scripts/checks_docflow_route.py
"""

from __future__ import annotations

LIMIT = 1_000_000
SLA = {"Юрист": 2, "Финансист": 2, "Руководитель": 1, "Директор": 1}


def route(amount: float, decisions: dict) -> list[str]:
    path = ["Инициация", "Юрист"]
    if decisions.get("Юрист") == "доработка":
        return path + ["Инициация"]
    path.append("Финансист")
    if decisions.get("Финансист") == "доработка":
        return path + ["Инициация"]
    path.append("Руководитель")
    if amount > LIMIT:
        path.append("Директор")
    path.append("Подписание")
    return path


def main() -> None:
    ok = route(500_000, {})
    assert ok == ["Инициация", "Юрист", "Финансист", "Руководитель", "Подписание"], ok
    print("[ok] договор в пределах лимита: 4 этапа к состоянию «подписан обеими сторонами»")

    big = route(2_000_000, {})
    assert "Директор" in big and big[-1] == "Подписание"
    print("[ok] ветвление по лимиту: сумма > 1 000 000 добавляет этап директора, прочих веток нет")

    back = route(500_000, {"Юрист": "доработка"})
    assert back[-1] == "Инициация"
    print("[ok] возврат на доработку: маршрут возвращается инициатору, а не умирает в задаче юриста")

    assert set(SLA) == {"Юрист", "Финансист", "Руководитель", "Директор"}
    assert sum(SLA[s] for s in ["Юрист", "Финансист", "Руководитель"]) == 5
    print("[ok] сроки этапов ролью, не фамилией: юрист 2 + финансист 2 + руководитель 1 = 5 дней до подписания")


if __name__ == "__main__":
    main()
